import Database from 'better-sqlite3';
import { expect, it } from 'vitest';
import { createApp } from '../app.js';
import { migrate } from '../db/migrate.js';
import { keyFromSecret } from '../crypto.js';
import { PlanRepository } from '../repos/plans.js';
import { RelevanceTrialService } from '../services/relevance-trial.js';
it('requires session and CSRF; ratings reject stale revisions and return non-cacheable owner data', async () => {
  const db = new Database(':memory:'); migrate(db);
  const now = new Date('2026-09-19T12:00:00Z');
  const config={NODE_ENV:'test' as const,DATABASE_PATH:':memory:',SESSION_SECRET:'test-session-secret-change-me-1234567890',APP_ORIGIN:'https://planner.example.test'};
  const member={id:'a',householdId:'h',accessSubject:'subject',displayName:'Owner',timezone:'America/New_York',active:true};
  db.prepare('INSERT INTO households (id, created_at) VALUES (?,?)').run('h',now.toISOString());
  db.prepare('INSERT INTO members (id,household_id,access_subject,display_name,timezone,active,created_at) VALUES (?,?,?,?,?,1,?)').run('a','h','subject','Owner','America/New_York',now.toISOString());
  const actor={memberId:'a',householdId:'h'},key=keyFromSecret(config.SESSION_SECRET);
  const id=new PlanRepository(db,key,()=>now).createPrivate(actor,{title:'Synthetic arrival',category:'other',participants:[],preparationTasks:[],unresolvedFields:[]});
  db.prepare("UPDATE plan_versions SET origin='extraction'").run();
  const item=new RelevanceTrialService(db,key,()=>now).prepare(actor,[id]).items[0]!;
  const app=createApp({db,config,now:()=>now,members:()=>[member],verifyAccess:async token=>token==='valid'?{subject:'subject'}:null});
  const path='/dashboard/api/v1/relevance-trial';
  expect((await app.request(path)).status).toBe(401);
  const bootstrap=await app.request('/dashboard/api/v1/session',{method:'POST',headers:{Authorization:'Bearer valid',Origin:config.APP_ORIGIN,'X-Planner-Bootstrap':'1'}});
  const csrf=(await bootstrap.json()).data.csrfToken;
  const headers={Authorization:'Bearer valid',Cookie:bootstrap.headers.get('set-cookie')!,Origin:config.APP_ORIGIN,'Content-Type':'application/json'};
  const body=JSON.stringify({value:'skip',expectedRevision:1});
  expect((await app.request(`${path}/${item.id}`,{method:'POST',headers,body})).status).toBe(403);
  const saved=await app.request(`${path}/${item.id}`,{method:'POST',headers:{...headers,'X-CSRF-Token':csrf},body});
  expect(saved.status).toBe(200);expect(saved.headers.get('cache-control')).toBe('no-store');
  expect((await saved.json()).data.items[0].value).toBe('skip');
  expect((await app.request(`${path}/${item.id}`,{method:'POST',headers:{...headers,'X-CSRF-Token':csrf},body})).status).toBe(409);
  const read=await app.request(path,{headers});expect(read.headers.get('cache-control')).toBe('no-store');
  const learningBody=JSON.stringify({enabled:true,expectedRevision:0,consentVersion:'personal-relevance-v1'});
  expect((await app.request(`${path}/learning`,{method:'POST',headers,body:learningBody})).status).toBe(403);
  const enabled=await app.request(`${path}/learning`,{method:'POST',headers:{...headers,'X-CSRF-Token':csrf},body:learningBody});
  expect(enabled.status).toBe(200);expect((await enabled.json()).data).toMatchObject({enabled:true,revision:1});
  expect((await app.request(`${path}/learning`,{method:'POST',headers:{...headers,'X-CSRF-Token':csrf},body:learningBody})).status).toBe(409);
  db.close();
});
